// Writes dist/types/astro.d.ts from dist/custom-elements.json. Attribute names come from the manifest;
// value types come from the TypeScript checker, so aliases such as ButtonSize expand to their unions.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';
import ts from 'typescript';

const MANIFEST = 'dist/custom-elements.json';
const OUT = 'dist/types/astro.d.ts';

const manifest = JSON.parse(readFileSync(MANIFEST, 'utf-8'));
const elements = manifest.modules.flatMap((mod) =>
	(mod.declarations ?? [])
		.filter((d) => d.customElement && d.tagName)
		.map((d) => ({ path: mod.path, name: d.name, tag: d.tagName, attributes: d.attributes ?? [] }))
);

const program = ts.createProgram(
	elements.map((e) => e.path),
	{ strict: true, target: ts.ScriptTarget.ES2022, experimentalDecorators: true }
);
const checker = program.getTypeChecker();

const classOf = (path, name) => {
	const source = program.getSourceFile(path);
	const node = source?.statements.find((s) => ts.isClassDeclaration(s) && s.name?.text === name);
	if (!node) throw new Error(`${name} not found in ${path}`);
	return checker.getTypeAtLocation(node);
};

/**
 * The attribute value type for a property. Booleans accept only `true` (Astro renders `{false}` on a
 * custom element as the string "false", which Lit reads as present), numbers also take numeric strings,
 * and `null`/`undefined` stay optional through the `?`.
 */
export const attributeType = (type) => {
	const parts = (type.isUnion() ? type.types : [type]).filter(
		(t) => !(t.flags & (ts.TypeFlags.Undefined | ts.TypeFlags.Null))
	);
	const out = new Set();
	for (const t of parts) {
		if (t.flags & ts.TypeFlags.BooleanLike) out.add('true');
		else if (t.flags & ts.TypeFlags.NumberLiteral) out.add(`${t.value}`).add(`'${t.value}'`);
		else if (t.flags & ts.TypeFlags.Number) out.add('number').add('`${number}`');
		else if (t.flags & ts.TypeFlags.StringLiteral) out.add(`'${t.value}'`);
		else out.add('string');
	}
	return [...out].join(' | ');
};

const entries = elements
	.sort((a, b) => a.tag.localeCompare(b.tag))
	.map(({ path, name, tag, attributes }) => {
		const cls = classOf(path, name);
		const props = attributes.map((attr) => {
			const symbol = cls.getProperty(attr.fieldName ?? attr.name);
			if (!symbol)
				throw new Error(`${tag}: no property ${attr.fieldName} for attribute ${attr.name}`);
			const type = checker.getTypeOfSymbol(symbol);
			return `\t\t\t'${attr.name}'?: ${attributeType(type)} | null | undefined;`;
		});
		return `\t\t'${tag}': HTMLAttributes & {\n${props.join('\n')}\n\t\t};`;
	});

const output = `// Generated by scripts/generate-framework-types.mjs from custom-elements.json. Do not edit.
// Opt in from src/env.d.ts: /// <reference types="@edgarjaymez/grove/astro" />
// Attribute names are kebab-case. Boolean attributes take \`true\` or nothing, never \`false\`: Astro
// renders \`{false}\` on a custom element as the string "false", which Lit reads as set.
// TypeScript skips excess-property checks on dashed names, so a misspelled dashed attribute is not
// caught; camelCase property names and \`false\` booleans are.
declare namespace astroHTML.JSX {
	interface IntrinsicElements {
${entries.join('\n')}
	}
}
`;

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, output);
console.log(`[grove] wrote ${OUT} (${elements.length} elements)`);
